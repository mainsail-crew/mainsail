/**
 * Announcements RPC Interface
 *
 * Moonraker announcements are effectively push notifications that can be used
 * to notify users of important information related to the development and
 * status of software in the Klipper ecosystem.
 *
 * @see https://moonraker.readthedocs.io/en/latest/external_api/announcements/
 */
export interface AnnouncementsRPC {
    /**
     * List announcements.
     * Retrieves a list of current announcements.
     */
    'server.announcements.list': (params?: {
        /** When set to false dismissed entries will be excluded from the returned list (default: true) */
        include_dismissed?: boolean
    }) => Promise<{
        /** An array of Announcement Entry objects, sorted by date in descending order (newest to oldest) */
        entries: AnnouncementEntry[]
        /** An array of RSS announcement feeds Moonraker is currently subscribed to */
        feeds: string[]
    }>

    /**
     * Update announcements.
     * Requests that Moonraker check for announcement updates. Generally not required
     * in production, as Moonraker automatically checks for updates every 30 minutes.
     */
    'server.announcements.update': (params?: {
        /**
         * Feeds to update (default: all subscribed feeds).
         * Not documented, but accepted by Moonraker.
         */
        subscriptions?: string[]
    }) => Promise<{
        /** An array of Announcement Entry objects, sorted by date in descending order (newest to oldest) */
        entries: AnnouncementEntry[]
        /** A value of true indicates that announcement entries were changed after the update operation */
        modified: boolean
    }>

    /**
     * Dismiss an announcement.
     * Sets the dismiss flag of an announcement to true.
     */
    'server.announcements.dismiss': (params: {
        /** The entry ID of the announcement to dismiss (required) */
        entry_id: string
        /**
         * A time, in seconds, after which the entry's dismissed flag will revert to false.
         * When omitted the entry remains dismissed indefinitely.
         *
         * Note: The docs list `null` as the default, but Moonraker rejects an explicit null
         * (it fails the int conversion), so the parameter must be omitted instead.
         */
        wake_time?: number
    }) => Promise<{
        /** The entry ID of the dismissed announcement entry */
        entry_id: string
    }>

    /**
     * List announcement feeds.
     * Returns the announcement feeds Moonraker is currently subscribed to.
     */
    'server.announcements.feeds': () => Promise<{
        /** An array of announcement feeds Moonraker is currently subscribed to */
        feeds: string[]
    }>

    /**
     * Subscribe to an announcement feed.
     * The feed name is converted to lowercase by Moonraker.
     */
    'server.announcements.post_feed': (params: {
        /** The name of the announcement feed to subscribe to (required) */
        name: string
    }) => Promise<{
        /** The name of the announcement feed subscribed to */
        feed: string
        /** The subscription action taken by Moonraker */
        action: AnnouncementFeedSubscribeAction
    }>

    /**
     * Remove an announcement feed.
     * Only feeds previously subscribed to via `server.announcements.post_feed` may be removed.
     * Feeds configured in moonraker.conf cannot be removed; an error is returned instead.
     */
    'server.announcements.delete_feed': (params: {
        /** The name of the announcement feed to remove (required) */
        name: string
    }) => Promise<{
        /** The name of the announcement feed removed */
        feed: string
        /** The action taken after the request. Will be 'removed' upon successful removal */
        action: 'removed'
    }>
}

/**
 * Announcement Priority
 *
 * - `normal`: Standard priority, front-ends decide how to present these
 * - `high`: High priority, front-ends should alert the user immediately
 */
export type AnnouncementPriority = 'normal' | 'high'

/**
 * Announcement Source
 *
 * - `moonlight`: Received from the moonlight GitHub repo (or local XML files in dev_mode)
 * - `internal`: Generated by Moonraker itself (e.g. by a component such as simplyprint)
 */
export type AnnouncementSource = 'moonlight' | 'internal'

/**
 * Announcement Feed Subscription Action
 *
 * - `added`: The requested announcement feed has been subscribed to
 * - `skipped`: Moonraker was already subscribed to the requested feed
 */
export type AnnouncementFeedSubscribeAction = 'added' | 'skipped'

/**
 * Announcement Entry
 *
 * Represents a single announcement as returned by Moonraker.
 */
export interface AnnouncementEntry {
    /** A unique identifier for the announcement entry */
    entry_id: string
    /** A url associated with the announcement. Links to a GitHub issue for moonlight announcements */
    url: string
    /** The title of the announcement */
    title: string
    /** A brief description of the announcement (truncated to 512 characters by moonlight) */
    description: string
    /** The priority of the announcement */
    priority: AnnouncementPriority
    /** The announcement creation date in unix time */
    date: number
    /** Set to true if the announcement has been dismissed */
    dismissed: boolean
    /** The date, in unix time, the announcement was last dismissed. null if not dismissed */
    date_dismissed: number | null
    /**
     * The date, in unix time, when the entry's dismissed flag reverts to false.
     * null if the announcement has not been dismissed or was dismissed indefinitely.
     *
     * Note: The docs describe this as "time remaining in seconds", but Moonraker
     * actually stores an absolute timestamp (`date_dismissed + wake_time`).
     */
    dismiss_wake: number | null
    /** The source of the announcement */
    source: AnnouncementSource
    /** The registered RSS feed (or internal component name) the announcement belongs to */
    feed: string
}

/**
 * Payload of the notify_announcement_update notification.
 * Emitted when announcement entries are added or removed.
 * @see https://moonraker.readthedocs.io/en/latest/external_api/jsonrpc_notifications/#announcement-update-event
 */
export interface AnnouncementUpdateNotification {
    /** The full list of current Announcement Entry objects */
    entries: AnnouncementEntry[]
}

/**
 * Payload of the notify_announcement_dismissed notification.
 * Emitted when an announcement is dismissed.
 * @see https://moonraker.readthedocs.io/en/latest/external_api/jsonrpc_notifications/#announcement-dismissed-event
 */
export interface AnnouncementDismissedNotification {
    /** The entry ID of the dismissed announcement */
    entry_id: string
}

/**
 * Payload of the notify_announcement_wake notification.
 * Emitted when a dismissed announcement's wake time has elapsed.
 * @see https://moonraker.readthedocs.io/en/latest/external_api/jsonrpc_notifications/#announcement-wake-event
 */
export interface AnnouncementWakeNotification {
    /** The entry ID of the announcement that woke */
    entry_id: string
}
